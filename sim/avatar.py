def _paths(avatar_path: str) -> dict[str, str]:
    """Every prim path this module touches, derived from one root."""
    return {
        "avatar": avatar_path,
        "body": f"{avatar_path}/body_mesh",
        "character": f"{avatar_path}/character",
        "rig": f"{avatar_path}/character/rig",
        "cam_fp": f"{avatar_path}/body_mesh/cam_first_person",
        "cam_tp": f"{avatar_path}/body_mesh/cam_third_person",
        "looks": f"{avatar_path}/Looks",
        "material": f"{avatar_path}/Looks/avatar_skin",
        "graph": f"{avatar_path}/Controls",
    }


def load_avatar_config(path: Path = SCENE_YAML) -> dict:
    """The avatar block of config/scene.yaml. The config is the contract."""
    with open(path, encoding="utf-8") as fh:
        return yaml.safe_load(fh)["avatar"]


