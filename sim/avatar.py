"""The avatar: the one moving entity in the observatory. Layer 1 (scene/USD).

Structure built (all paths under the REAL stage root ``/Root`` -- there is no
``/World`` on this stage; confirmed in the GUI 2026-08-15)::

    /Root/Avatar                    Xform, identity, never moves
      +-- Looks/avatar_skin         UsdPreviewSurface + non-visual "skin"
      +-- body_mesh                 Capsule -- collision. PhysX moves this one.
      |     |                       INVISIBLE: it collides, it does not render.
      |     +-- cam_first_person    eye height, looks along travel
      |     +-- cam_third_person    3 m behind, 1.6 m up, pitched down 25 deg
      +-- character                 what you SEE: the warehouse's rigged Worker,
      |     +-- rig                 referenced. Follows body_mesh via the graph.
      +-- Controls                  OmniGraph: character controller + the follow

Why the cameras hang off ``body_mesh`` and not off ``/Root/Avatar``
-------------------------------------------------------------------
Physics moves the *capsule*, not its parent. Cameras parented to the Xform
would stay behind while the body walked away -- a silent failure of exactly the
kind this project keeps a list of. They are still descendants of the Avatar
Xform, switching view is still just rebinding the viewport, and nothing ever
drives a camera directly. ``/Root/Avatar`` is deliberately left at identity:
the character controller writes a *world* pose back onto the capsule, so a
non-identity parent would teleport the avatar on the first simulated frame.

Why a PhysX character controller and not a kinematic rigid body
----------------------------------------------------------------
The gate for this task is "walking into a shelf stops you". A kinematic rigid
body **cannot** do that: PhysX moves a kinematic actor to its target pose
unconditionally and does not depenetrate it, so it drives straight through
static geometry. Kinematic-vs-static contacts are not even generated by
default. The requirement "kinematic, not dynamic" and the requirement "the
shelf stops you" are not jointly satisfiable by a rigid body.

``PhysxCharacterControllerAPI`` is the resolution and is what the requirement
was reaching for. PhysX implements a CCT *as* a kinematic actor -- the schema's
own doc for ``scaleCoeff`` says "scale coefficient for underlying kinematic
actor" -- so nothing here ragdolls, trips, or falls through a floor. On top of
that it does collide-and-slide against static geometry, which is the half a
kinematic body cannot do.

Two consequences, both deliberate:

  * The capsule carries **no** ``UsdPhysics.CollisionAPI``. A prim with
    CollisionAPI and no rigid body is *static* collision geometry, so applying
    it here would park a static capsule inside the character controller's own
    actor and fight it. The CCT is the collision representation.
  * What ray-based sensors bounce off is **render** geometry, not colliders --
    RTX lidar and radar trace the same BVH the renderer does. So the avatar
    needs a visible mesh for its own sake, and that is ``character``, not the
    capsule. The capsule is hidden with ``visibility = "invisible"`` and keeps
    ``purpose = "default"``; NVIDIA's own CCT demo hides its capsule with
    ``purpose = "guide"`` instead, which is inherited and would take the
    character down with it. ``verify_avatar.py`` asserts both halves: the
    capsule does not render, and the character does.

Execution model
---------------
This script creates prims and saves USD. It reads no sensor data, so exec mode
(see CLAUDE.md) does not apply and ``SimulationApp`` is correct. It does need
Kit running, for the asset resolver and for the OmniGraph node registry.

Reused rather than written (hard rule 4)
----------------------------------------
The control wiring is NVIDIA's, from two shipped examples:

  * ``isaacsim.examples.interactive.omnigraph_keyboard`` -- Isaac Examples ->
    Input Devices -> Omnigraph Keyboard. Read first, as instructed. What it
    actually does: builds an ``omni.graph.action`` execution graph in which
    ``OnTick`` (``onlyPlayback=True``) drives ``ReadKeyboardState`` nodes for
    'A' and 'D', converts their booleans to doubles, negates one, scales the
    sum by 0.1, and read-modify-writes a prim attribute through
    ``ReadPrimAttribute`` -> ``Add`` -> ``WritePrimAttribute``. It resizes a
    cube. The transferable part is the accumulator pattern, not the graph.
  * ``omni.physx.cct`` -> Physics demos -> Character Controller -> "Action
    Graph" (``data/demos/actiongraph.usd``). Same idea, finished: an
    ``OnStageEvent('Simulation Start Play')`` activates an
    ``omni.physx.cct.OgnCharacterController`` node, whose ``setupControls =
    "Auto"`` binds WASD/E/Q and gamepad for us. That is the wiring below, with
    the demo's arrow-key rebinding and its ``purpose="guide"`` capsule dropped,
    and its centimetre-stage numbers converted to metres.

Controls, once you press Play (defaults from
``omni.physxcct.scripts.utils.setup_controls``)::

    W / S   forward / back   (world -X / +X -- MEASURED, not read off the
    A / D   left / right      control code, which looks like it means +X. The
    E / Q   jump / down       controller inverts X and not Y; see _FORWARD_X.
                              Movement is world-axis: it does not follow the
                              view, because the view cannot be turned.)

The second entry point: :func:`set_avatar_pose`
------------------------------------------------
Episode reset needs to place the avatar from code, repeatedly, without
restarting the simulator, and every benchmark this project is aimed at
(HM3D, MP3D, GOAT-Bench, HM3D-OVON, A-EQA) begins each episode by doing
exactly that. :func:`set_avatar_pose` is that call. It is an **addition**, not
a replacement: it touches neither the Controls graph nor the controller's
registration, so the keyboard keeps working and simply carries on from
wherever the pose was written.

It is a pose WRITE, which is not the same thing as a walk. See that function's
docstring for which route it takes through -- or around -- the character
controller, and for what "not collide-and-slide" costs.
``sim/verify_avatar_pose.py`` is the headless check that it lands and that a
fixed sensor sees it land.

Run::

    docker compose -f docker/docker-compose.yml run --rm sim \\
        ./python.sh /workspace/sim/avatar.py
"""

